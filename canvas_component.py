def _ensure_frontend_dir() -> str:
    """Write the embedded frontend to a versioned dir and return it.

    Prefer a directory next to this module — the standard, most robust
    location for Streamlit component serving (a stale-process reload can
    otherwise leave the component pointing at a vanished temp path).
    Fall back to the system temp dir if the app directory is not
    writable.
    """
    digest = hashlib.md5(_EMBEDDED_HTML.encode("utf-8")).hexdigest()[:12]
    dirname = f"canvas_frontend_runtime_{digest}"
    candidates = [
        os.path.join(os.path.dirname(os.path.abspath(__file__)), dirname),
        os.path.join(tempfile.gettempdir(), f"mmr_canvas_{digest}"),
    ]
    last_exc: Optional[OSError] = None
    for d in candidates:
        try:
            p = os.path.join(d, "index.html")
            if not os.path.isfile(p):
                os.makedirs(d, exist_ok=True)
                with open(p, "w", encoding="utf-8") as f:
                    f.write(_EMBEDDED_HTML)
            return d
        except OSError as exc:  # noqa: BLE001 - try the next candidate
            last_exc = exc
            continue
    raise RuntimeError(
        "could not write canvas frontend to any location"
    ) from last_exc


_canvas = components.declare_component(
    "mm_recap_canvas", path=_ensure_frontend_dir()
)

CANVAS_DEFAULT: Dict = {
    "blur_boxes": [],
    "subtitle": {"x_pct": 0.5, "y_pct": 0.82, "font_size_pct": 0.055},
    "action": None,
}


def interactive_canvas(
    video_id: Optional[str],
    video_data_url: Optional[str],
    blur_boxes: List[Dict],
    subtitle: Dict,
    subtitles_enabled: bool = True,
    canvas_aspect: str = "9 / 16",
    local_picked: bool = False,
    video_ack: Optional[str] = None,
    preview: Optional[Dict] = None,
    subtitle_style: Optional[Dict] = None,
    # Deferred upload: a fresh nonce per Run click when Python needs
    # the picked video. None = no upload requested; the frontend sends
    # the stored video_data exactly once per nonce.
    upload_request: Optional[int] = None,
    key: Optional[str] = None,
) -> Dict:
    """Render the canvas and return the latest user-edited state.

    ``canvas_aspect`` is the SOURCE video's own ratio (e.g. "1280 / 720"),
    so the phone mockup matches the uploaded video — independent of the
    output aspect setting. ``local_picked`` tells the frontend the video
    is already loaded in-frame (picked locally), so it must not reload.
    ``video_ack`` tells the frontend the server has saved the picked
    file, so it can drop the base64 payload from its component value
    (otherwise the ~40MB would be re-sent on every rerun).
    ``preview`` (Step 16) is the Source-tab settings dict
    (aspect_ratio / fit_mode / crop_align / inner_scale / vertical_pos /
    horizontal_pos / mirror_horizontal / copyright_zoom) — the frontend
    applies them as a live CSS preview (phone aspect, crop framing,
    pad layout, mirror, zoom) without touching the edit coordinates.
    """
    value = _canvas(
        video_id=video_id,
        video_data_url=video_data_url,
        blur_boxes=blur_boxes or [],
        subtitle=subtitle or dict(CANVAS_DEFAULT["subtitle"]),
        subtitles_enabled=bool(subtitles_enabled),
        canvas_aspect=canvas_aspect,
        local_picked=bool(local_picked),
        video_ack=video_ack,
        preview=preview or {},
        subtitle_style=subtitle_style or {},
        upload_request=upload_request,
        default=CANVAS_DEFAULT,
        key=key,
    )
    if not isinstance(value, dict):
        return dict(CANVAS_DEFAULT)
    value.setdefault("blur_boxes", [])
    value.setdefault("subtitle", dict(CANVAS_DEFAULT["subtitle"]))
    value.setdefault("action", None)
    return value
